create or replace function public.audit_club_stats_change()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_entity_type text;
  v_entity_key text;
begin
  -- Ignore migration/seed writes executed without an authenticated editor.
  if auth.uid() is null then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  if tg_table_name = 'club_player_stats' then
    v_entity_type := 'player';
    v_entity_key := coalesce(to_jsonb(new) ->> 'id', to_jsonb(old) ->> 'id');
  else
    v_entity_type := 'season';
    v_entity_key := coalesce(to_jsonb(new) ->> 'ordinal', to_jsonb(old) ->> 'ordinal');
  end if;

  insert into public.club_stats_audit (
    entity_type,
    entity_key,
    action,
    changed_by,
    changed_by_email,
    before_data,
    after_data
  )
  values (
    v_entity_type,
    v_entity_key,
    lower(tg_op),
    auth.uid(),
    auth.jwt() ->> 'email',
    case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) else null end,
    case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) else null end
  );

  insert into public.club_stats_last_edit (
    entity_type,
    entity_key,
    changed_at,
    changed_by,
    changed_by_email
  )
  values (
    v_entity_type,
    v_entity_key,
    now(),
    auth.uid(),
    auth.jwt() ->> 'email'
  )
  on conflict (entity_type, entity_key)
  do update set
    changed_at = excluded.changed_at,
    changed_by = excluded.changed_by,
    changed_by_email = excluded.changed_by_email;

  if tg_op = 'DELETE' then
    return old;
  end if;

  return new;
end;
$$;

