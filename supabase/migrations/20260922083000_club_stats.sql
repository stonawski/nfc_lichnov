-- Club historical statistics editable from the NFC Lichnov admin.
-- Apply through the Supabase SQL editor or migration workflow before using /admin/statistiky.

create table if not exists public.club_player_stats (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) > 0),
  goals integer not null default 0 check (goals >= 0),
  matches integer not null default 0 check (matches >= 0),
  source_order integer not null unique,
  facr_player_id bigint,
  active boolean not null default false,
  needs_review boolean not null default false,
  updated_at timestamptz
);

create table if not exists public.club_seasons (
  ordinal integer primary key,
  season text not null unique check (char_length(trim(season)) > 0),
  matches integer not null default 0 check (matches >= 0),
  record text not null default '',
  score text not null default '',
  points integer not null default 0,
  competition text not null default '',
  position integer not null default 0 check (position >= 0),
  incomplete boolean not null default false,
  outcome text check (outcome in ('promotion', 'relegation')),
  next_competition text,
  updated_at timestamptz
);

create table if not exists public.club_stats_audit (
  id bigint generated always as identity primary key,
  entity_type text not null check (entity_type in ('player', 'season')),
  entity_key text not null,
  action text not null check (action in ('insert', 'update', 'delete')),
  changed_at timestamptz not null default now(),
  changed_by uuid,
  changed_by_email text,
  before_data jsonb,
  after_data jsonb
);

create table if not exists public.club_stats_last_edit (
  entity_type text not null check (entity_type in ('player', 'season')),
  entity_key text not null,
  changed_at timestamptz not null,
  changed_by uuid,
  changed_by_email text,
  primary key (entity_type, entity_key)
);

create index if not exists club_player_stats_facr_idx
  on public.club_player_stats (facr_player_id)
  where facr_player_id is not null;

create index if not exists club_player_stats_active_idx
  on public.club_player_stats (active, matches desc, goals desc);

create index if not exists club_stats_audit_entity_idx
  on public.club_stats_audit (entity_type, entity_key, changed_at desc);

